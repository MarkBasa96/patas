// Phase 7: turn the importer's preview into SQL that loads it into ONE account, safely re-runnable.
//   node tools/import/load-sql.mjs <owner-user-id> [import/preview.json]
// Writes (all inside the gitignored import/ folder, because they hold the owner's real data):
//   import/load.sql       the load: runs as the owner (privacy rules on), skips rows whose source_key exists
//   import/reconcile.sql  the check: recomputes every debt's remaining in the database and compares it,
//                         plus a fingerprint of every imported row, with what this PC expects
// Prints only counts, the expected total and the fingerprint (no names, no per-debt amounts).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { balance, fmt } from './balance.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const uid = process.argv[2];
if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(uid || '')) {
  console.error('usage: node tools/import/load-sql.mjs <owner-user-id> [preview.json]');
  process.exit(2);
}
const preview = JSON.parse(readFileSync(process.argv[3] || join(root, 'import', 'preview.json'), 'utf8'));
const { debts, installments, lines } = preview;

// Refuse anything a tool could silently change in transit: only printable ASCII, plus tab and newline,
// which travel as plain placeholder words and are turned back into chr(9) / chr(10) by the database.
const BACKSLASH = String.fromCharCode(92), TAB = String.fromCharCode(9), NL = String.fromCharCode(10);
const P_TAB = '~patas-tab~', P_NL = '~patas-nl~';
for (const r of [...debts, ...installments, ...lines]) {
  for (const [k, v] of Object.entries(r)) {
    if (typeof v !== 'string') continue;
    for (const ch of v) {
      const c = ch.charCodeAt(0);
      if (c !== 9 && c !== 10 && (c < 32 || c > 126)) throw new Error(`unsafe character ${c} in ${r.source_key}.${k}`);
    }
    if (v.includes(BACKSLASH) || v.includes(P_TAB) || v.includes(P_NL)) throw new Error(`backslash or placeholder in ${r.source_key}.${k}`);
  }
}
const TAG = '$patas_import$';
const json = (rows) => {
  const safe = rows.map((r) => Object.fromEntries(Object.entries(r).map(([k, v]) => [k, typeof v === 'string' ? v.split(TAB).join(P_TAB).split(NL).join(P_NL) : v])));
  const s = JSON.stringify(safe);
  if (s.includes(TAG) || s.includes(BACKSLASH)) throw new Error('payload would break the SQL quoting');
  return TAG + s + TAG;
};
// Lines go in parts so each statement stays small enough to hand-check if it is ever pasted.
const chunks = (rows, n) => Array.from({ length: Math.ceil(rows.length / n) }, (_, k) => rows.slice(k * n, k * n + n));
const back = (col) => `replace(replace(${col}, '${P_TAB}', chr(9)), '${P_NL}', chr(10))`;

// The same row text on both sides (JS here, SQL in reconcile.sql), so the fingerprints can be compared.
const v = (x) => (x === null || x === undefined ? '' : typeof x === 'boolean' ? (x ? 't' : 'f') : String(x));
const rowText = {
  debts: (r) => ['D', r.source_key, r.id, r.direction, r.kind, r.person_name, r.title, r.due_on, r.opened_on, r.settled_on, r.remind, r.note, r.deleted].map(v).join('|'),
  installments: (r) => ['I', r.source_key, r.id, r.debt_id, r.seq, r.due_on, r.amount_centavos, r.deleted].map(v).join('|'),
  lines: (r) => ['L', r.source_key, r.id, r.debt_id, r.kind, r.charge_kind, r.adjust_sign, r.amount_centavos, r.on_date, r.note, r.deleted].map(v).join('|'),
};
const all = [...debts.map(rowText.debts), ...installments.map(rowText.installments), ...lines.map(rowText.lines)].sort();
const fingerprint = createHash('md5').update(all.join('\n'), 'utf8').digest('hex');

// What each debt should come to, by the same rules the app and the dry run use.
const expected = debts.map((d) => {
  const b = balance(d, installments.filter((i) => i.debt_id === d.id), lines.filter((l) => l.debt_id === d.id));
  return { id: d.id, remaining: b.remaining, overpaid: b.overpaid };
});
const active = debts.filter((d) => !d.settled_on);
const totalActive = expected.filter((e) => active.some((d) => d.id === e.id)).reduce((s, e) => s + e.remaining, 0);

const claims = JSON.stringify({ sub: uid, role: 'authenticated' });
const load = `-- Phase 7 load for one account. Generated by tools/import/load-sql.mjs. Re-runnable: existing source keys are skipped.
begin;
select set_config('request.jwt.claims', '${claims}', true);
set local role authenticated;
with ins as (
  insert into public.debts (id, direction, kind, person_name, title, due_on, opened_on, settled_on, remind, qr_id, note, source_key, created_at, deleted)
  select id, direction, kind, ${back('person_name')}, ${back('title')}, due_on, opened_on, settled_on, remind, qr_id, ${back('note')}, source_key, created_at, deleted
  from jsonb_to_recordset(${json(debts)}::jsonb) as t(id text, direction text, kind text, person_name text, title text, due_on date, opened_on date, settled_on date, remind boolean, qr_id text, note text, source_key text, created_at bigint, deleted boolean)
  on conflict (user_id, source_key) do nothing returning 1)
select 'debts inserted' as what, count(*) as n from ins;
with ins as (
  insert into public.installments (id, debt_id, seq, due_on, amount_centavos, source_key, created_at, deleted)
  select id, debt_id, seq, due_on, amount_centavos, source_key, created_at, deleted
  from jsonb_to_recordset(${json(installments)}::jsonb) as t(id text, debt_id text, seq int, due_on date, amount_centavos bigint, source_key text, created_at bigint, deleted boolean)
  on conflict (user_id, source_key) do nothing returning 1)
select 'installments inserted' as what, count(*) as n from ins;
${chunks(lines, 80).map((part, k) => `with ins as (
  insert into public.debt_lines (id, debt_id, kind, charge_kind, adjust_sign, amount_centavos, on_date, note, source_key, created_at, deleted)
  select id, debt_id, kind, charge_kind, adjust_sign, amount_centavos, on_date, ${back('note')}, source_key, created_at, deleted
  from jsonb_to_recordset(${json(part)}::jsonb) as t(id text, debt_id text, kind text, charge_kind text, adjust_sign smallint, amount_centavos bigint, on_date date, note text, source_key text, created_at bigint, deleted boolean)
  on conflict (user_id, source_key) do nothing returning 1)
select 'lines inserted (part ${k + 1})' as what, count(*) as n from ins;`).join('\n')}
commit;
`;

// reconcile.sql: {{SHIFT}} lets the negative control change one amount inside a rolled-back transaction.
const reconcile = `-- Phase 7 reconcile for one account. Generated by tools/import/load-sql.mjs.
with u as (select '${uid}'::uuid as id),
d as (select x.* from public.debts x, u where x.user_id = u.id and x.source_key is not null),
i as (select x.* from public.installments x, u where x.user_id = u.id and x.source_key is not null),
l as (select x.* from public.debt_lines x, u where x.user_id = u.id and x.source_key is not null),
rows as (
  select concat_ws('|', 'D', source_key, id, direction, kind, coalesce(person_name, ''), coalesce(title, ''), coalesce(due_on::text, ''), coalesce(opened_on::text, ''), coalesce(settled_on::text, ''), case when remind then 't' else 'f' end, coalesce(note, ''), case when deleted then 't' else 'f' end) as t from d
  union all
  select concat_ws('|', 'I', source_key, id, debt_id, seq::text, due_on::text, amount_centavos::text, case when deleted then 't' else 'f' end) from i
  union all
  select concat_ws('|', 'L', source_key, id, debt_id, kind, coalesce(charge_kind, ''), coalesce(adjust_sign::text, ''), amount_centavos::text, on_date::text, coalesce(note, ''), case when deleted then 't' else 'f' end) from l
),
calc as (
  select d.id, d.settled_on,
    coalesce((select sum(amount_centavos) from i where i.debt_id = d.id and not i.deleted), 0)
    + coalesce((select sum(amount_centavos) from l where l.debt_id = d.id and not l.deleted
                and not (kind in ('payment', 'writeoff') or (kind = 'adjustment' and adjust_sign = -1))), 0)
    - coalesce((select sum(amount_centavos) from l where l.debt_id = d.id and not l.deleted
                and (kind in ('payment', 'writeoff') or (kind = 'adjustment' and adjust_sign = -1))), 0) as net
  from d
),
exp as (select * from jsonb_to_recordset(${json(expected)}::jsonb) as e(id text, remaining bigint, overpaid bigint))
select
  (select count(*) from d) as debts, (select count(*) from i) as installments, (select count(*) from l) as lines,
  (select md5(string_agg(t, chr(10) order by t collate "C")) from rows) as fingerprint,
  (select count(*) from calc where settled_on is null) as active_debts,
  (select sum(greatest(net, 0)) from calc where settled_on is null) as total_active_centavos,
  (select count(*) from calc where settled_on is not null and greatest(net, 0) = 0) as settled_at_zero,
  (select count(*) from calc full join exp using (id)
     where calc.id is null or exp.id is null or greatest(calc.net, 0) <> exp.remaining or greatest(-calc.net, 0) <> exp.overpaid) as mismatched_debts,
  (select count(*) from u, auth.users au where au.id <> u.id) as other_users,
  (select count(*) from public.debts x, u where x.user_id <> u.id) + (select count(*) from public.debt_lines x, u where x.user_id <> u.id) as rows_in_other_accounts;
`;
writeFileSync(join(root, 'import', 'load.sql'), load);
writeFileSync(join(root, 'import', 'reconcile.sql'), reconcile);
console.log(`rows: ${debts.length} debts, ${installments.length} installments, ${lines.length} lines`);
console.log(`active debts: ${active.length}, total left ${fmt(totalActive)} (centavos ${totalActive})`);
console.log(`settled debts: ${debts.length - active.length}, all at 0.00: ${expected.filter((e) => !active.some((d) => d.id === e.id)).every((e) => e.remaining === 0)}`);
console.log(`expected fingerprint: ${fingerprint}`);
console.log(`wrote import/load.sql (${load.length} chars) and import/reconcile.sql (${reconcile.length} chars)`);
